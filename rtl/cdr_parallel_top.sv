`timescale 1ns/1ps
`default_nettype none
// -----------------------------------------------------------------------------
// Quarter-rate parallel RX top: sampler bank + 4-way BBPD + decimated loop +
// gearbox, producing aligned words and lock at 2 Gb/s with a 500 MHz
// quarter-rate clock.
//
// Data path (one 4-UI group per clk_q cycle):
//   data_in -> sampler_bank (8 phase-clocked receiver_sampler leaves)
//           -> raw_q[7:0] (clk_q-domain capture)
//           -> pi_code rotator: eff_data[i] = raw[(2i + pi) % 8],
//              eff_edge[i] = raw[(2i + 1 + pi) % 8]
//           -> cdr_parallel_bbpd (summed Alexander vote)
//           -> cdr_decimated_loop (once per DECIM UI) -> pi_code
//           -> rx_parallel_gearbox (slip-repaired bit stream -> words)
//           -> rx_parallel_align  (word rotation + skid)
//
// pi_code -> sampling phase mapping: pi_code is a rotation r of the 8-phase
// grid.  data phase i samples the grid point (2i + r) mod 8, edge phase i the
// grid point (2i + 1 + r) mod 8.  One pi_code step shifts all sampling
// instants by 0.5 UI (45 deg of the 500 MHz clock); a net walk of 2 steps is
// a 1-UI shift of the quarter-rate group boundary and is reported to the
// gearbox as a slip.
//
// Stage B (real clocking): clk_ph here is an ideal 8-phase 500 MHz clock
// generated by the TB.  When the multiphase_clock/PI block lands, clk_ph is
// re-timed by pi_code (either walking the sampling phases or interpolating
// between two adjacent DCO phases - see docs/rx_parallel_spec.md); clk_q is
// then divided from the re-timed clock, the pi_code rotator above becomes
// unnecessary (keep it as a deskew aid), and the +-1-UI boundary shifts
// happen physically at the clk_q divider, with the slip reporting as a
// consistency check.
// -----------------------------------------------------------------------------
module cdr_parallel_top #(
    parameter int PH_W            = 3,
    parameter int FREQ_FRAC       = 8,
    parameter int DECIM           = 16,   // UI per loop update (125 MHz @ 2 Gb/s)
    parameter int KI              = 1,
    parameter int KP_SHIFT        = 5,
    parameter int LEAK_UI_BITS    = 12,
    parameter int LOCK_EDGES      = 16,
    parameter int LOCK_STALE_BITS = 16,
    parameter int FRAC_BITS       = 12,
    parameter int DATA_W          = 16,
    // 0 (v1 with PI-timed clocks, the TB re-times clk_ph/clk_q from
    // pi_code+pi_frac): the rotator is bypassed.  1: ideal fixed clocks, the
    // pi_code rotator remaps the bank samples.
    parameter bit ROT_EN          = 1'b0
) (
    input  wire                      clk_q,
    input  wire [7:0]                clk_ph,    // 8 phases, 45 deg apart @ 500 MHz
    input  wire                      rst_n,
    input  wire                      enable,
    input  wire                      data_in,   // serial NRZ @ 2 Gb/s
    input  wire [PH_W-1:0]           phase_init,
    output wire [DATA_W-1:0]         rx_word,
    output wire                      word_valid,
    output wire                      lock,
    output wire                      lock_stale,
    output wire                      slip_evt,    // elastic event (1 cycle)
    output wire [1:0]                slip_drop,   // duplicated bits to drop
    output wire [1:0]                slip_insert, // skipped bits to fill
    output wire [PH_W-1:0]           pi_code,
    output wire signed [FRAC_BITS:0] freq_trim
);

    wire [3:0] bank_data_q, bank_edge_q;
    wire [7:0] bank_raw_q;

    sampler_bank u_bank (
        .data_in (data_in),
        .clk_ph  (clk_ph),
        .clk_q   (clk_q),
        .rst_n   (rst_n),
        .data_q  (bank_data_q),
        .edge_q  (bank_edge_q),
        .raw_q   (bank_raw_q)
    );

    // pi_code rotator: emulate the re-timed sampler.  pi_code r delays every
    // sampling instant by r taps (0.25 ns each).  Virtual data tap i of bank
    // cycle g samples at T_g + 0.1875 + 0.25*(2i + r); raw indices <= 7 fall
    // inside cycle g's own bank capture, indices >= 8 fall into cycle g+1's
    // (the delay pushes the late taps past the clk_q boundary).  The group is
    // therefore assembled one bank cycle late, from a 2-deep raw history
    // (raw_d2 = capture of window [T-2, T), raw_d1 = capture of [T, T+2)),
    // which keeps the four data taps (and the four edge taps) in strict time
    // order for every r.  Content continuity across cycles is automatic for
    // 1-tap dither steps; a net 2-tap walk = 1 UI boundary shift and is the
    // slip the loop reports.
    //
    // Stage B: with a real PI, clk_ph itself is re-timed and clk_q (divided
    // from it) moves with it, so the wrap never crosses a bank-cycle boundary
    // and this history pipeline reduces to a plain wire.
    reg  [PH_W-1:0] rot_d;
    reg  [7:0]      raw_d1_q, raw_d2_q;   // captures of the two previous windows
    reg  [3:0]      eff_data;
    reg  [3:0]      eff_edge;


    always_ff @(posedge clk_q or negedge rst_n) begin
        if (!rst_n) begin
            raw_d1_q  <= 8'b0;
            raw_d2_q  <= 8'b0;
            rot_d     <= {PH_W{1'b0}};
            eff_data  <= 4'b0;
            eff_edge  <= 4'b0;
        end else begin
            raw_d1_q <= bank_raw_q;
            raw_d2_q <= raw_d1_q;
            rot_d    <= pi_c;
            // Delayed virtual window [T, T+2): taps with idx <= 7 fall inside
            // it (capture raw_d2 = window [T-2, T) shifted... see comment
            // above); taps with idx >= 8 spill into the next window
            // (raw_d1).  Both are stable before this edge.
            for (int i = 0; i < 4; i++) begin
                if (ROT_EN) begin
                    eff_data[i] <= ((2*i + rot_d) <= 7)
                            ? raw_d2_q[2*i + rot_d]
                            : raw_d1_q[2*i + rot_d - 8];
                    eff_edge[i] <= ((2*i + 1 + rot_d) <= 7)
                            ? raw_d2_q[2*i + 1 + rot_d]
                            : raw_d1_q[2*i + 1 + rot_d - 8];
                end else begin
                    eff_data[i] <= raw_d2_q[2*i];
                    eff_edge[i] <= raw_d2_q[2*i + 1];
                end
            end
        end
    end

    wire signed [2:0] vote;
    wire              vote_valid;

    cdr_parallel_bbpd #(.DECIM(DECIM)) u_bbpd (
        .clk_q      (clk_q),
        .rst_n      (rst_n),
        .enable     (enable),
        .data_q     (eff_data),
        .edge_q     (eff_edge),
        .vote       (vote),
        .vote_valid (vote_valid)
    );

    wire [PH_W-1:0] pi_c;
    wire            slip_evt_c;
    wire [PH_W-1:0] slip_pi_c;
    wire [1:0]      slip_drop_c, slip_insert_c;

    cdr_decimated_loop #(
        .PH_W(PH_W), .FREQ_FRAC(FREQ_FRAC), .DECIM(DECIM), .KI(KI),
        .KP_SHIFT(KP_SHIFT), .LEAK_UI_BITS(LEAK_UI_BITS),
        .LOCK_EDGES(LOCK_EDGES), .LOCK_STALE_BITS(LOCK_STALE_BITS),
        .FRAC_BITS(FRAC_BITS), .CLK_FOLLOW(1'b0)
    ) u_loop (
        .clk_q      (clk_q),
        .rst_n      (rst_n),
        .enable     (enable),
        .vote       (vote),
        .vote_valid (vote_valid),
        .phase_init (phase_init),
        .pi_code    (pi_c),
        .lock       (lock),
        .lock_stale (lock_stale),
        .slip_evt   (slip_evt_c),
        .slip_pi    (slip_pi_c),
        .slip_drop  (slip_drop_c),
        .slip_insert(slip_insert_c),
        .freq_trim  (freq_trim)
    );

    wire [DATA_W-1:0] gb_word;
    wire              gb_valid;

    rx_parallel_gearbox #(.DATA_W(DATA_W)) u_gearbox (
        .clk_q      (clk_q),
        .rst_n      (rst_n),
        .enable     (enable),
        .data_q     (eff_data),
        .slip_evt   (slip_evt_c),
        .slip_drop  (slip_drop_c),
        .slip_insert(slip_insert_c),
        .rx_word    (gb_word),
        .word_valid (gb_valid)
    );

    rx_parallel_align #(.DATA_W(DATA_W)) u_align (
        .clk_q         (clk_q),
        .rst_n         (rst_n),
        .enable        (enable),
        .align_rot     (2'b00),
        .word_in       (gb_word),
        .word_in_valid (gb_valid),
        .word_out      (rx_word),
        .word_out_valid(word_valid)
    );

    assign pi_code    = pi_c;
    assign slip_evt   = slip_evt_c;
    assign slip_drop  = slip_drop_c;
    assign slip_insert= slip_insert_c;

endmodule
