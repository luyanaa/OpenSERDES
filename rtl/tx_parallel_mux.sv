`timescale 1ns/1ps
`default_nettype none

// -----------------------------------------------------------------------------
// Quarter-rate TX parallel MUX -- final serializer stage ("Stage A").
//
// Architecturally a real 4:1 parallel MUX tree, NOT a 1-bit-per-serial-clock
// shift register: a 4-bit parallel nibble enters at the 500 MHz word rate and
// leaves as a 2 Gb/s serial stream.  Serialization is done by clock PHASES,
// not by a fast clock: every flop in this module is clocked at 500 MHz.  The
// digital loop never runs at line rate.
//
// Clock contract (all clocks 500 MHz, 50% duty, 2 ns period):
//   clk_ph[0..3] : ideal multiphase clocks, rising edges 90 deg (500 ps)
//                  apart, in the order ph0 -> ph1 -> ph2 -> ph3.  In the final
//                  system these come from the PLL/phase-rotator macro; for
//                  Stage A they are ideal inputs generated by the TB.
//   clk_word     : nibble/word clock.  Its rising edge leads clk_ph[0] by
//                  250 ps (a quarter period).  nibble_in is retimed in the
//                  clk_word domain (here, when RETIME_INPUT=1) and stays
//                  stable from that clk_word edge through the ph3 edge, so
//                  all four phase edges sample the same nibble.
//
// One serial UI = 500 ps (4 UIs per word clock).
//
// Pipeline / retiming -- one comment per stage so synthesis keeps the stages
// separate (do NOT let ABC re-merge these into one combinational path):
//   Stage 0 (clk_word domain): nibble_q <= nibble_in.  The only clk_word flop;
//     this is the retimed parallel word feeding the phase domains.
//   Stage L1 (phase domains): two 2:1 latch-MUX branches, one flop per phase.
//     Flop p is clocked ONLY by clk_ph[p], captures its bit 250 ps after
//     nibble_q updates (full quarter-period setup margin) and drives exactly
//     the one UI whose phase clocked it.  Even branch = {ph0, ph2} (bits 0,2),
//     odd branch = {ph1, ph3} (bits 1,3).
//   Stage L2 (final): 2:1 phase-selected mux between the two 1 Gb/s branches;
//     the select is decoded from the phases themselves, so the output changes
//     exactly on each phase edge -- one bit per 500 ps UI.
//
// SDC note (500 MHz domain): declare 5 clocks (clk_word, clk_ph[0..3]) with
// clk_word leading ph0 by 250 ps and ph_k leading ph_{k+1} by 500 ps.  The
// only clk_word -> clk_ph paths are the Stage 0 -> L1 captures below.
//
// Future generator hookup: a `rate_mode: quarter` in gen_ip.py would emit
// this module as the TX last stage with the 4 phase clocks bound to the
// clock-macro outputs (currently ideal TB sources).
// -----------------------------------------------------------------------------
module tx_parallel_mux #(
    parameter bit LSB_FIRST    = 1'b1,   // nibble_in[0] leaves first, on ph0
    parameter bit RETIME_INPUT = 1'b1    // insert the Stage-0 clk_word retiming flop
) (
    input  wire        clk_word,         // 500 MHz nibble-rate word clock
    input  wire [3:0]  clk_ph,           // ideal 500 MHz phases, 90 deg apart
    input  wire        rst_n,
    input  wire        enable,           // 0: hold last nibble / last bits
    input  wire [3:0]  nibble_in,        // parallel nibble from clk_word domain
    output logic       serial_out
);

    // ---------------------------------------------------------------------
    // Stage 0: clk_word-domain retiming of the parallel nibble.
    // nibble_in is produced in the clk_word domain (PRBS front / gearbox),
    // so this is a same-domain flop, not a CDC.
    // ---------------------------------------------------------------------
    logic [3:0] nibble_q;
    generate
        if (RETIME_INPUT) begin : g_retime
            always_ff @(posedge clk_word or negedge rst_n) begin
                if (!rst_n)      nibble_q <= 4'b0000;
                else if (enable) nibble_q <= nibble_in;
            end
        end else begin : g_retime_bypass
            assign nibble_q = nibble_in;   // upstream already retimed it
        end
    endgenerate

    wire [3:0] nib;
    assign nib = LSB_FIRST ? nibble_q
                           : {nibble_q[0], nibble_q[1], nibble_q[2], nibble_q[3]};

    // ---------------------------------------------------------------------
    // Stage L1: two 2:1 latch-MUX branches, retimed per phase.
    //   even branch select = clk_ph[1]: low at the ph0 edge (picks bit 0),
    //     high from the ph1 edge through the ph2 edge (picks bit 2).
    //   odd branch select = clk_ph[2]: low at the ph1 edge (picks bit 1),
    //     high from the ph2 edge through the ph3 edge (picks bit 3).
    // Each flop is clocked by exactly one phase and holds its bit for the
    // one UI that follows, i.e. the mux select and the retiming edge are the
    // same phase -- the latch-MUX property that keeps the branches
    // skew-matched and prevents comb merging.
    // ---------------------------------------------------------------------
    wire mux_even = clk_ph[1] ? nib[2] : nib[0];
    wire mux_odd  = clk_ph[2] ? nib[3] : nib[1];

    logic even0_q, even2_q;   // even branch: ph0 slot / ph2 slot
    logic odd1_q,  odd3_q;    // odd branch:  ph1 slot / ph3 slot

    always_ff @(posedge clk_ph[0] or negedge rst_n) begin
        if (!rst_n)      even0_q <= 1'b0;
        else if (enable) even0_q <= mux_even;
    end
    always_ff @(posedge clk_ph[2] or negedge rst_n) begin
        if (!rst_n)      even2_q <= 1'b0;
        else if (enable) even2_q <= mux_even;
    end
    always_ff @(posedge clk_ph[1] or negedge rst_n) begin
        if (!rst_n)      odd1_q <= 1'b0;
        else if (enable) odd1_q <= mux_odd;
    end
    always_ff @(posedge clk_ph[3] or negedge rst_n) begin
        if (!rst_n)      odd3_q <= 1'b0;
        else if (enable) odd3_q <= mux_odd;
    end

    // ---------------------------------------------------------------------
    // Stage L2: FINAL STAGE -- 2:1 phase-selected mux between the two
    // 1 Gb/s branches.  Branch-internal selects pick which retimed bit is
    // currently driven; even_active is high exactly during the ph0 and ph2
    // UIs, so serial_out changes on every phase edge (1 bit / 500 ps).
    // (The select decode is static comb logic; the data inputs are phase-
    // retimed flops, so a select decode transition can only glitch for a
    // delta cycle at UI boundaries, never corrupt a settled UI.)
    // ---------------------------------------------------------------------
    wire even_active = (clk_ph[0] & ~clk_ph[1]) | (clk_ph[2] & ~clk_ph[3]);
    wire even_pair   = clk_ph[2] ? even2_q : even0_q;
    wire odd_pair    = clk_ph[3] ? odd3_q  : odd1_q;

    assign serial_out = even_active ? even_pair : odd_pair;

endmodule

`default_nettype wire
